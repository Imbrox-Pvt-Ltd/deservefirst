/**
 * Platform CLI · scaffold.mjs
 * Templates for `platform module:new`. The CLI is the executable form of the
 * Module Standard (§18): a developer or agent never hand-writes boilerplate or
 * re-decides structure, so all modules are structurally identical by
 * construction and `platform check` passes the moment they are generated.
 * Layer: tooling.
 */

const pascal = (value) =>
  value.split(/[-_]/).map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');

const camel = (value) => {
  const p = pascal(value);
  return p.charAt(0).toLowerCase() + p.slice(1);
};

const title = (value) =>
  value.split(/[-_]/).map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join(' ');

/**
 * Returns the complete file set for a new module. Every file already carries its
 * §33.2 header, so the generated module is compliant before a line is written.
 */
